// Display language: English by default, German switchable (footer EN | DE).
//
// The English text is the key: t("Overview") gives "Overview" in English
// and the DE entry in German. {name} placeholders are filled from `vars`.
// N_("...") only marks a string for translation where t() runs later
// (lookup tables); tests/test_i18n.py checks that every t()/N_() string and
// every data-i18n attribute has a German entry.
//
// Choice: browser (localStorage "fis.lang") > fis.ini `language` > English.
// Game terms (FSS, DSS, boxel, genus names, star classes) stay as the game
// writes them.

let current = "en";

export function lang() { return current; }
export function locale() { return current === "de" ? "de-DE" : "en-GB"; }
export function N_(s) { return s; }

export function t(s, vars) {
  let r = (current === "de" && DE[s]) || s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  return r;
}

export async function initLang() {
  let l = null;
  try { l = localStorage.getItem("fis.lang"); } catch (e) { l = null; }
  if (!l) {
    try {
      const r = await fetch("/api/config", { cache: "no-store" });
      if (r.ok) l = (await r.json()).language;
    } catch (e) { l = null; }
  }
  current = l === "de" ? "de" : "en";
  document.documentElement.lang = current;
}

export function setLang(l) {
  try { localStorage.setItem("fis.lang", l === "de" ? "de" : "en"); } catch (e) { /* private mode */ }
  location.reload();
}

/** Static markup: data-i18n="English text" (text) and data-i18n-title (tooltip). */
export function applyStatic(root = document) {
  for (const n of root.querySelectorAll("[data-i18n]")) n.textContent = t(n.dataset.i18n);
  for (const n of root.querySelectorAll("[data-i18n-title]")) n.title = t(n.dataset.i18nTitle);
}

